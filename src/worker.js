import {handleAPI} from './api.js';
import html from '../dist/index.html';
import css from '../dist/styles.css';
import app from '../dist/app.js?raw';
import rules from '../dist/rules.js?raw';
import liveSession from '../dist/live-session.js?raw';
import poseEngine from '../dist/pose-engine.js?raw';
import frontCounter from '../dist/front-counter.js?raw';
import replay from '../dist/replay.js?raw';
import replayHTML from '../dist/replay.html';
const files={'/':[html,'text/html; charset=utf-8'],'/index.html':[html,'text/html; charset=utf-8'],'/styles.css':[css,'text/css'],'/app.js':[app,'text/javascript'],'/rules.js':[rules,'text/javascript'],'/live-session.js':[liveSession,'text/javascript']};
Object.assign(files,{'/front-counter.js':[frontCounter,'text/javascript'],'/pose-engine.js':[poseEngine,'text/javascript'],'/replay.js':[replay,'text/javascript'],'/replay.html':[replayHTML,'text/html; charset=utf-8']});
export default {async fetch(request,env){const path=new URL(request.url).pathname;let response;
  if(path.startsWith('/api/'))response=await handleAPI(request,env);
  else if(files[path])response=new Response(files[path][0],{headers:{'content-type':files[path][1],'cache-control':'no-cache'}});
  else response=new Response('Not found',{status:404});
  response.headers.set('X-Content-Type-Options','nosniff');
  response.headers.set('Referrer-Policy','strict-origin-when-cross-origin');
  response.headers.set('Permissions-Policy','camera=(self), microphone=()');
  return response;
}};
